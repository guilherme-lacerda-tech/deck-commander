class GS:
    def __init__(self):
        self.m = bytearray(4 << 20)

    def _a32(self, bp, bw, x, y):
        page = (y // 32) * bw + (x // 64)
        blk = BT32[(y % 32) // 8][(x % 64) // 8]
        return ((bp + page * 32 + blk) * 64 + CT32[y % 8][x % 8]) * 4

    def escreve32(self, dados, bp, bw, w, h):
        i = 0
        for y in range(h):
            for x in range(w):
                a = self._a32(bp, bw, x, y)
                self.m[a:a + 4] = dados[i:i + 4]
                i += 4

    def le32(self, bp, bw, w, h):
        out = bytearray()
        for y in range(h):
            for x in range(w):
                a = self._a32(bp, bw, x, y)
                out += self.m[a:a + 4]
        return bytes(out)

    def _a4(self, bp, bw, x, y):
        page = (y // 128) * (bw // 2) + (x // 128)
        blk = BT4[(y % 128) // 16][(x % 128) // 32]
        n = CT4[y % 16][x % 32]
        return (bp + page * 32 + blk) * 512 + n  # em nibbles

    def le4(self, bp, bw, w, h):
        px = bytearray(w * h)
        for y in range(h):
            for x in range(w):
                n = self._a4(bp, bw, x, y)
                b = self.m[n >> 1]
                px[y * w + x] = (b >> 4) if n & 1 else (b & 15)
        return bytes(px)

    def escreve4(self, px, bp, bw, w, h):
        for y in range(h):
            for x in range(w):
                n = self._a4(bp, bw, x, y)
                v = px[y * w + x] & 15
                b = self.m[n >> 1]
                self.m[n >> 1] = ((b & 0x0F) | (v << 4)) if n & 1 else ((b & 0xF0) | v)

    def _a8(self, bp, bw, x, y):
        page = (y // 64) * (bw // 2) + (x // 128)
        blk = BT8[(y % 64) // 16][(x % 128) // 16]
        n = CT8[y % 16][x % 16]
        return (bp + page * 32 + blk) * 256 + n

    def le8(self, bp, bw, w, h):
        return bytes(self.m[self._a8(bp, bw, x, y)] for y in range(h) for x in range(w))
